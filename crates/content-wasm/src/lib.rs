//! No session, identity, network, storage, devices or caller-selected resource
//! URLs: run this parser/codec only inside the separate browser content worker.
#![forbid(unsafe_code)]

use nuschl_content::ContentRenderer;
use nuschl_core::{ContentBlock, EMBED, MAX_CONTENT_BYTES, MessageDocument};
use serde::Serialize;
use std::io::{self, Write};
#[cfg(all(target_arch = "wasm32", target_os = "unknown"))]
use wasm_bindgen::prelude::*;

pub const MAX_IMAGE_INPUT: usize = 8 * 1024 * 1024;
pub const MAX_REPLY_BYTES: usize = 2 * 1024 * 1024;
pub const MAX_PIXEL_BYTES: usize = 640 * 1024;

#[derive(Serialize)]
pub struct Rendered {
    /// Derivatives only. The SDK retains original source/mode as its authority.
    pub marked_text: String,
    pub plain_text: String,
    pub document: MessageDocument,
}

#[derive(Serialize)]
pub struct EncodedImage {
    /// Generated by the reviewed encoder, never forwarded arbitrary input HTML.
    pub html: String,
    pub thumbnail: ContentBlock,
}

/// Retain only the shared renderer's bounded, lazily loaded highlighting data.
#[cfg_attr(all(target_arch = "wasm32", target_os = "unknown"), wasm_bindgen)]
#[derive(Default)]
pub struct ContentProcessor {
    renderer: ContentRenderer,
}

#[cfg_attr(all(target_arch = "wasm32", target_os = "unknown"), wasm_bindgen)]
impl ContentProcessor {
    #[cfg_attr(
        all(target_arch = "wasm32", target_os = "unknown"),
        wasm_bindgen(constructor)
    )]
    pub fn new() -> Self {
        Self::default()
    }

    /// `plain` is literal message text; `legacy` is stock Mumble HTML;
    /// `marked` is a previously normalized derivative, never an authentication
    /// assertion. The caller must retain and bind the original source itself.
    pub fn render_message(&self, source: &str, mode: &str) -> Result<String, String> {
        if source.len() > MAX_CONTENT_BYTES {
            return Err("Message exceeds the content limit.".into());
        }
        let marked_text = match mode {
            "plain" | "marked" => source.to_owned(),
            "legacy" => self.renderer.legacy_plain_text(source).map_err(error)?,
            _ => return Err("Unsupported content mode.".into()),
        };
        let plain_text = marked_text.split(EMBED).step_by(2).collect();
        let mut document = self.renderer.render(&marked_text).map_err(error)?;
        constrain_document(&mut document)?;
        json(&Rendered {
            marked_text,
            plain_text,
            document,
        })
    }

    pub fn encode_image(&self, bytes: &[u8], limit: usize) -> Result<String, String> {
        image_input(bytes)?;
        if !(64..=MAX_CONTENT_BYTES).contains(&limit) {
            return Err("Invalid image message limit.".into());
        }
        let (html, mut thumbnail) =
            nuschl_content::encode_image_message(bytes, limit).map_err(error)?;
        let mut pixels = 0;
        constrain_image(&mut thumbnail, &mut pixels)?;
        json(&EncodedImage { html, thumbnail })
    }

    /// Decode only supplied image bytes. No URI, path or URL enters this API.
    /// Initial browser viewers use the same finite thumbnail dimensions as
    /// messages, rather than allowing caller-selected decoded allocations.
    pub fn decode_image(&self, bytes: &[u8]) -> Result<String, String> {
        image_input(bytes)?;
        let mut image = nuschl_content::decode_image(
            bytes,
            nuschl_content::MAX_IMAGE_WIDTH,
            nuschl_content::MAX_IMAGE_HEIGHT,
        )
        .ok_or("Unsupported or invalid image.")?;
        let mut pixels = 0;
        constrain_image(&mut image, &mut pixels)?;
        json(&image)
    }
}

fn error(error: impl std::fmt::Display) -> String {
    error.to_string()
}

fn image_input(bytes: &[u8]) -> Result<(), String> {
    if bytes.is_empty() || bytes.len() > MAX_IMAGE_INPUT {
        return Err("Image input exceeds the content limit.".into());
    }
    Ok(())
}

fn constrain_document(document: &mut MessageDocument) -> Result<(), String> {
    if document.blocks.len() > 512 {
        return Err("Document exceeds the block limit.".into());
    }
    let mut pixels = 0;
    let mut images = 0;
    for block in &mut document.blocks {
        if matches!(block, ContentBlock::Image { .. }) {
            images += 1;
            if images > 8 {
                return Err("Document exceeds the image limit.".into());
            }
            constrain_image(block, &mut pixels)?;
        }
    }
    Ok(())
}

fn constrain_image(block: &mut ContentBlock, total: &mut usize) -> Result<(), String> {
    let ContentBlock::Image {
        width,
        height,
        rgba,
        source,
    } = block
    else {
        return Err("The codec did not return pixels.".into());
    };
    let bytes = (*width as usize)
        .checked_mul(*height as usize)
        .and_then(|pixels| pixels.checked_mul(4))
        .filter(|_| *width > 0 && *height > 0)
        .ok_or("Invalid image dimensions.")?;
    *total = total
        .checked_add(bytes)
        .ok_or("Image pixel limit exceeded.")?;
    if *total > MAX_PIXEL_BYTES || rgba.len() != bytes.div_ceil(3) * 4 {
        return Err("Image pixel limit exceeded.".into());
    }
    // UI consumers get pixels only, without an encoded resource to load or a
    // decoder to invoke. The SDK retains original source separately.
    *source = None;
    Ok(())
}

/// Bound serialization while writing; checking after to_string() would first
/// allocate an arbitrarily expanded highlighted document.
fn json(value: &impl Serialize) -> Result<String, String> {
    struct Reply(Vec<u8>);
    impl Write for Reply {
        fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
            if bytes.len() > MAX_REPLY_BYTES - self.0.len() {
                return Err(io::Error::other("Content reply exceeds its byte limit."));
            }
            self.0.extend_from_slice(bytes);
            Ok(bytes.len())
        }
        fn flush(&mut self) -> io::Result<()> {
            Ok(())
        }
    }
    let mut reply = Reply(Vec::new());
    serde_json::to_writer(&mut reply, value).map_err(error)?;
    String::from_utf8(reply.0).map_err(error)
}
