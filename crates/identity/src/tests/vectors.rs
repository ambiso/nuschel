//! Known-answer tests.
//!
//! - `test-vectors/identity-v1.txt`: every Nuschl format from fixed seeds, for other
//!   implementations. Regenerate (only for a deliberate format change, which needs a new
//!   version) with `NUSCHL_UPDATE_VECTORS=1 cargo test -p nuschl-identity vectors`;
//!   that also refreshes the fuzz seeds in `fuzz/seeds/identity/`.
//! - `test-vectors/composite-mldsa65-ed25519.txt`: RFC 10073's vector for the composite.

use std::fmt::Write as _;

use crate::certificate::DeviceSigningAuthority;
use crate::crypto::{Secret32, composite, ed25519, mldsa65};
use crate::keys::{
    DeviceId, DeviceKeys, DeviceSigningKey, DisplayName, HybridPublicKey, HybridSecret,
    IdentityRoot,
};
use crate::keystore::{DeviceKeystore, RecoveryBlob, RecoveryKey, StoreKey};
use crate::{
    DeviceCertificate, DeviceCredential, DeviceRevocation, DeviceRoster, DeviceSigningCertificate,
    SafetyNumber, SafetyQr, Validity, VerifiedIdentity, WHOLE_DEVICE,
};

const VECTORS: &str = include_str!("../../test-vectors/identity-v1.txt");
const COMPOSITE: &str = include_str!("../../test-vectors/composite-mldsa65-ed25519.txt");

/// 32 bytes `tag, tag+1, …, tag+31`.
fn seed_bytes(tag: u8) -> [u8; 32] {
    std::array::from_fn(|i| tag.wrapping_add(i as u8))
}

fn seed(tag: u8) -> Secret32 {
    Secret32::from_slice(&seed_bytes(tag)).unwrap()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex(text: &str) -> Vec<u8> {
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&text[i..i + 2], 16).unwrap())
        .collect()
}

/// `name = hex` lines of a vector file.
fn field<'a>(file: &'a str, name: &str) -> &'a str {
    file.lines()
        .find_map(|line| line.strip_prefix(name)?.strip_prefix(" = "))
        .unwrap_or_else(|| panic!("no field {name}"))
}

const T0: u64 = 1_800_000_000;

struct Vectors {
    text: String,
    seeds: Vec<(&'static str, Vec<u8>)>,
}

fn generate() -> Vectors {
    let mut t = String::new();
    let mut seeds = Vec::new();
    macro_rules! line {
        ($($arg:tt)*) => { writeln!(t, $($arg)*).unwrap() };
    }
    line!("# Nuschl identity v1 test vectors (crates/identity, docs/e2ee.md §3, §4).");
    line!("# Byte strings are hex. seed(x) is the 32 bytes x, x+1, ..., x+31 (mod 256).");
    line!("# ML-DSA-65 signs deterministically here (FIPS 204, rnd = 0^32); production");
    line!("# signing is hedged, so only these vectors are reproducible byte for byte.");
    line!("# Composite: RFC 10073 id-MLDSA65-Ed25519-SHA512. Ed25519: RFC 8032.");
    line!("# Generated by `NUSCHL_UPDATE_VECTORS=1 cargo test -p nuschl-identity vectors`.");

    // Identity root and device-signing key.
    let root = IdentityRoot::from_secret(HybridSecret::from_seeds(seed(0x00), seed(0x20)));
    let dsk = DeviceSigningKey::from_secrets(
        HybridSecret::from_seeds(seed(0x40), seed(0x60)),
        seed(0x80),
    );
    let dsk_cert = root
        .certify_device_signing_key_with(&dsk, 1, T0, [0; 32])
        .unwrap();
    let identity = VerifiedIdentity::verify(root.public_key().clone(), dsk_cert.clone()).unwrap();
    let authority = DeviceSigningAuthority::new(dsk, dsk_cert.clone()).unwrap();
    line!();
    line!("[identity root]");
    line!("mldsa65_seed = {}", hex(&seed_bytes(0x00)));
    line!("ed25519_seed = {}", hex(&seed_bytes(0x20)));
    line!("public_key = {}", hex(&root.public_key().encode()));
    line!("# SHA-256(0x1f || \"nuschl/identity-fingerprint/v1\" || public_key)");
    line!("fingerprint = {}", hex(root.fingerprint().as_bytes()));
    seeds.push(("hybrid-public-key", root.public_key().encode()));

    line!();
    line!("[device-signing key, generation 1]");
    line!("mldsa65_seed = {}", hex(&seed_bytes(0x40)));
    line!("ed25519_seed = {}", hex(&seed_bytes(0x60)));
    line!("credential_seed = {}", hex(&seed_bytes(0x80)));
    line!(
        "public_key = {}",
        hex(&authority.certificate().device_signing_key().encode())
    );
    line!(
        "credential_key = {}",
        hex(authority.certificate().credential_key().as_bytes())
    );
    line!("created_at = {T0}");
    line!("# root signs, ctx \"nuschl/device-signing-certificate/v1\"");
    line!("certificate = {}", hex(&dsk_cert.encode()));
    seeds.push(("device-signing-certificate", dsk_cert.encode()));

    // A device.
    let device = DeviceKeys::from_seeds(
        DeviceId::from_bytes(std::array::from_fn(|i| 0xd0 + i as u8)),
        1,
        seed(0xa0),
        seed(0xc0),
    )
    .unwrap();
    let validity = Validity::new(T0, T0 + 400 * 86_400).unwrap();
    let name = DisplayName::new("laptop").unwrap();
    let (cert, credential) = authority
        .certify_device_with(&device.public_keys(), &name, validity, [0; 32])
        .unwrap();
    let revocation = authority
        .revoke_device_with(device.device_id(), WHOLE_DEVICE, T0 + 1, [0; 32])
        .unwrap();
    line!();
    line!("[device]");
    line!("device_id = {}", hex(device.device_id().as_bytes()));
    line!("key_epoch = 1");
    line!("leaf_seed = {}", hex(&seed_bytes(0xa0)));
    line!("kem_seed = {}", hex(&seed_bytes(0xc0)));
    line!("leaf_key = {}", hex(device.leaf_key().as_bytes()));
    line!("# X-Wing (draft-connolly-cfrg-xwing-kem-06+, MLKEM768-X25519) from kem_seed");
    line!("kem_key = {}", hex(device.kem_key().as_bytes()));
    line!("not_before = {}", validity.not_before());
    line!("not_after = {}", validity.not_after());
    line!("display_name = laptop");
    line!("# device-signing key signs, ctx \"nuschl/device-certificate/v1\"");
    line!("certificate = {}", hex(&cert.encode()));
    line!("certificate_sha256 = {}", hex(&cert.hash()));
    line!("# credential key signs 0x1c || \"nuschl/device-credential/v1\" || body");
    line!("credential = {}", hex(&credential.encode()));
    line!("# revokes every key epoch; ctx \"nuschl/device-revocation/v1\"");
    line!("revoked_at = {}", T0 + 1);
    line!("revocation = {}", hex(&revocation.encode()));
    seeds.push(("device-certificate", cert.encode()));
    seeds.push(("device-credential", credential.encode()));
    seeds.push(("device-revocation", revocation.encode()));

    // The vectors verify.
    let mut roster = DeviceRoster::new(identity.clone());
    roster.add_certificate(cert.clone()).unwrap();
    roster
        .check_credential(&credential, device.leaf_key().as_bytes(), T0)
        .unwrap();
    roster.add_revocation(revocation.clone()).unwrap();

    // Safety numbers.
    let other = IdentityRoot::from_secret(HybridSecret::from_seeds(seed(0xe0), seed(0xf0)));
    let number = SafetyNumber::new(&root.fingerprint(), &other.fingerprint());
    let qr = SafetyQr::new(&root.fingerprint(), &other.fingerprint());
    line!();
    line!("[safety number]");
    line!("other_mldsa65_seed = {}", hex(&seed_bytes(0xe0)));
    line!("other_ed25519_seed = {}", hex(&seed_bytes(0xf0)));
    line!(
        "other_fingerprint = {}",
        hex(other.fingerprint().as_bytes())
    );
    line!("digits = {number}");
    line!("qr = {}", hex(qr.as_bytes()));
    seeds.push(("safety-qr", qr.as_bytes().to_vec()));

    // Recovery key and blob.
    let recovery_key = RecoveryKey::from_bytes(&[0x55; 32]);
    let blob = RecoveryBlob::seal_with_salt(&root, &recovery_key, [0x11; 32]).unwrap();
    line!();
    line!("[recovery]");
    line!("recovery_key = {}", hex(&[0x55; 32]));
    line!("recovery_key_display = {}", &*recovery_key.display());
    line!("salt = {}", hex(&[0x11; 32]));
    line!("recovery_blob = {}", hex(&blob.encode()));
    seeds.push(("recovery-blob", blob.encode()));
    assert_eq!(
        blob.open(&recovery_key).unwrap().fingerprint(),
        root.fingerprint()
    );

    // Keystore.
    let store_key = StoreKey::from_bytes(&[0x22; 32]);
    let device_copy = DeviceKeys::from_seeds(
        device.device_id(),
        1,
        device.leaf_seed.duplicate(),
        device.kem_seed.duplicate(),
    )
    .unwrap();
    let store = DeviceKeystore::new(
        identity.clone(),
        device_copy,
        cert.clone(),
        credential.clone(),
    )
    .unwrap()
    .with_device_signing(authority.duplicate())
    .unwrap()
    .with_recovery_blob(blob.clone());
    let sealed_store = store.seal_with_salt(&store_key, [0x33; 32]).unwrap();
    line!();
    line!("[device keystore]");
    line!("store_key = {}", hex(&[0x22; 32]));
    line!("salt = {}", hex(&[0x33; 32]));
    line!("# device keystore with the device-signing secret and the recovery blob");
    line!("sealed = {}", hex(&sealed_store));
    seeds.push(("sealed-keystore", sealed_store.clone()));
    let reopened = DeviceKeystore::open(&store_key, &sealed_store).unwrap();
    assert_eq!(reopened.device().public_keys(), device.public_keys());

    // Device-linking key schedule (SPAKE2 and HPKE are randomized; the schedule is not).
    let pake_existing: [u8; 33] = std::array::from_fn(|i| if i == 0 { b'A' } else { i as u8 });
    let pake_new: [u8; 33] = std::array::from_fn(|i| if i == 0 { b'B' } else { 0x80 + i as u8 });
    let (transcript, confirmation, psk) = crate::link::key_schedule(
        &[0x44; 32],
        &pake_existing,
        &pake_new,
        &device.public_keys(),
        &DisplayName::new("phone").unwrap(),
    );
    line!();
    line!("[device linking key schedule]");
    line!("# K from SPAKE2, both SPAKE2 messages as sent, the new device's keys (the [device]");
    line!("# above) named \"phone\"");
    line!("spake2_key = {}", hex(&[0x44; 32]));
    line!("pake_existing = {}", hex(&pake_existing));
    line!("pake_new = {}", hex(&pake_new));
    line!("transcript = {}", hex(&transcript));
    line!("confirmation = {}", hex(&confirmation));
    line!("psk = {}", hex(&psk));

    Vectors { text: t, seeds }
}

#[test]
fn identity_vectors_match_the_file() {
    let vectors = generate();
    if std::env::var_os("NUSCHL_UPDATE_VECTORS").is_some() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        std::fs::write(dir.join("test-vectors/identity-v1.txt"), &vectors.text).unwrap();
        let seeds = dir.join("../../fuzz/seeds/identity");
        std::fs::create_dir_all(&seeds).unwrap();
        for (name, bytes) in &vectors.seeds {
            std::fs::write(seeds.join(format!("{name}.bin")), bytes).unwrap();
        }
        return;
    }
    assert!(
        vectors.text == VECTORS,
        "the encodings changed; a format change needs a new version (see the module docs)"
    );
}

#[test]
fn identity_vectors_decode_and_verify() {
    let root = HybridPublicKey::decode(&unhex(field(VECTORS, "public_key"))).unwrap();
    assert_eq!(
        hex(root.fingerprint().as_bytes()),
        field(VECTORS, "fingerprint")
    );
    let dsk_cert = DeviceSigningCertificate::decode(&unhex(field(VECTORS, "certificate"))).unwrap();
    let identity = VerifiedIdentity::verify(root, dsk_cert).unwrap();
    let section = &VECTORS[VECTORS.find("[device]").unwrap()..];
    let cert = DeviceCertificate::decode(&unhex(field(section, "certificate"))).unwrap();
    let credential = DeviceCredential::decode(&unhex(field(section, "credential"))).unwrap();
    let revocation = DeviceRevocation::decode(&unhex(field(section, "revocation"))).unwrap();
    let leaf = unhex(field(section, "leaf_key"));
    let mut roster = DeviceRoster::new(identity);
    roster.add_certificate(cert).unwrap();
    roster.check_credential(&credential, &leaf, T0).unwrap();
    roster.add_revocation(revocation).unwrap();
    assert!(roster.check_credential(&credential, &leaf, T0).is_err());
    let digits = field(VECTORS, "digits");
    assert_eq!(SafetyNumber::parse(digits).unwrap().to_string(), digits);
}

#[test]
fn rfc_10073_composite_vector() {
    let pk = unhex(field(COMPOSITE, "pk"));
    let sk = unhex(field(COMPOSITE, "sk"));
    let m = unhex(field(COMPOSITE, "m"));
    let ctx = unhex(field(COMPOSITE, "ctx"));
    let s: Box<[u8; composite::SIGNATURE_LEN]> = unhex(field(COMPOSITE, "s"))
        .into_boxed_slice()
        .try_into()
        .unwrap();
    let s_ctx: Box<[u8; composite::SIGNATURE_LEN]> = unhex(field(COMPOSITE, "s_with_context"))
        .into_boxed_slice()
        .try_into()
        .unwrap();
    let (mldsa_pk, ed_pk) = pk.split_at(mldsa65::PUBLIC_KEY_LEN);
    let mldsa_pk: &[u8; mldsa65::PUBLIC_KEY_LEN] = mldsa_pk.try_into().unwrap();
    let ed_pk: &[u8; 32] = ed_pk.try_into().unwrap();

    // Their signatures verify with our implementation.
    composite::verify(mldsa_pk, ed_pk, b"", &m, &s).unwrap();
    composite::verify(mldsa_pk, ed_pk, &ctx, &m, &s_ctx).unwrap();
    assert!(composite::verify(mldsa_pk, ed_pk, &ctx, &m, &s).is_err());
    assert!(composite::verify(mldsa_pk, ed_pk, b"", &m, &s_ctx).is_err());
    let mut broken = s.clone();
    broken[100] ^= 1;
    assert!(composite::verify(mldsa_pk, ed_pk, b"", &m, &broken).is_err());

    // Their private key derives their public key with our implementation, and our
    // signatures verify under it.
    let mldsa_seed: [u8; 32] = sk[..32].try_into().unwrap();
    let ed_seed: [u8; 32] = sk[32..].try_into().unwrap();
    assert_eq!(&mldsa65::public_from_seed(&mldsa_seed)[..], &mldsa_pk[..]);
    assert_eq!(&ed25519::public_from_seed(&ed_seed), ed_pk);
    let ours = composite::sign(&mldsa_seed, &ed_seed, &ctx, &m, [7; 32]).unwrap();
    composite::verify(mldsa_pk, ed_pk, &ctx, &m, &ours).unwrap();
    // Ed25519 is deterministic, so our Ed25519 half equals theirs.
    assert_eq!(
        ours[mldsa65::SIGNATURE_LEN..],
        s_ctx[mldsa65::SIGNATURE_LEN..]
    );

    // The same key in Nuschl's encoding.
    let mut encoded = vec![0xFE, 0x01];
    encoded.extend_from_slice(&pk);
    HybridPublicKey::decode(&encoded).unwrap();
}
