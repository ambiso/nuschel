def via_text(path):
    return "\u2190".join("#%d" % number for number in path)


def priority_text(record):
    text = record["effective_priority"]
    if record["priority_source"] == "default":
        text += "~"
    elif record["priority_source"] == "prerequisite":
        text += "^ via " + via_text(record["priority_via"])
    return text


def claim_text(record):
    claim = record["claim"]
    if not claim:
        return "-"
    if not claim["active"]:
        return "%s expired" % claim["agent"]
    return "%s until %sZ" % (claim["agent"], claim["lease_until"][5:16].replace("T", " "))


def render_table(result, rows, show_all, width):
    lines = []
    oid = (result["default_branch_oid"] or "")[:8]
    todo = result["todo_map"]
    lines.append("%s @ %s %s: %d open, %d eligible%s; %d active local claim(s); showing %d. TODO map %s (%d rows)."
                 % (result["repository"], result["default_branch"], oid, result["open_issues"],
                    result["eligible_issues"],
                    "".join([" (in-progress counted)" if result["include_in_progress"] else "",
                             " (assigned counted)" if result["include_assigned"] else ""]),
                    result["active_claims"], len(rows),
                    "verified" if todo["verified"] else "UNVERIFIED", todo["rows"]))
    header = ["Q", "ISSUE", "PRIO", "+1", "APPROVAL", "BLOCKED", "PROG", "HOLDS", "CLAIM"]
    if show_all:
        header.append("ELIG")
    body = []
    for record in rows:
        holds = record["holds"] + (["assigned:" + ",".join(record["assignees"])] if record["assignees"] else [])
        cells = [str(record["queue_position"] or "-"), "#%d" % record["number"],
                 priority_text(record), str(record["thumbs_up"]), approval_text(record),
                 ",".join(record["blocked_by"]) or "-", "yes" if record["in_progress"] else "-",
                 ",".join(holds) or "-", claim_text(record)]
        if show_all:
            cells.append("yes" if record["eligible"] else "no")
        body.append(cells)
    widths = [max([len(header[i])] + [len(row[i]) for row in body]) for i in range(len(header))]
    used = sum(widths) + 2 * len(widths)
    title_width = max(20, width - used)

    def line(cells, title):
        return "  ".join(cell.ljust(widths[i]) for i, cell in enumerate(cells)) + "  " + title
    lines.append(line(header, "TITLE"))
    for cells, record in zip(body, rows, strict=True):
        title = record["title"]
        if len(title) > title_width:
            title = title[:title_width - 1] + "…"
        lines.append(line(cells, title).rstrip())
    footnotes = ["#%d %s" % (record["number"], note) for record in rows for note in record["notes"]]
    lines.append("Legend: ~ unset priority (medium default); ^ via #A\u2190#B = inherited from approved #A, "
                 "which waits for #B, which waits for this (priority only, never approval); "
                 "Q = queue position among eligible issues; CLAIM = local claim (UTC).")
    lines += footnotes
    lines += attention_lines(result)
    lines += ["warning: " + warning for warning in result["warnings"]]
    rate = result.get("rate_limit")
    if rate:
        lines.append("GraphQL rate limit: %s remaining (last page cost %s)."
                     % (rate.get("remaining"), rate.get("cost")))
    return "\n".join(lines)


def attention_lines(result):
    """Prerequisites of approved work that only a human can clear."""
    by_number = {record["number"]: record for record in result["issues"]}
    lines = []
    for item in result["attention_blockers"]:
        blocks = ", ".join("#%d (%s)" % (n, by_number[n]["effective_priority"]) for n in item["blocks"])
        kind = "UNAPPROVED BLOCKER" if item["kind"] == "needs approval" else "HELD BLOCKER"
        lines.append("%s: #%d blocks %s -- %s (%s)" % (kind, item["number"], blocks, item["kind"], item["title"][:60]))
    return lines


def node_state(record):
    if record["eligible"]:
        return "ELIGIBLE (Q%d)" % record["queue_position"]
    return "; ".join(record["ineligible_reasons"])


def node_label(record):
    return "#%d [%s] %s" % (record["number"], priority_text(record), record["title"][:70])


def adjacency(result):
    prerequisites = {record["number"]: [] for record in result["issues"]}
    dependents = {record["number"]: [] for record in result["issues"]}
    for blocker, dependent, kind in result["dependency_edges"]:
        prerequisites[dependent].append((blocker, kind))
        dependents[blocker].append((dependent, kind))
    return prerequisites, dependents


def dependency_tree(number, graph, by_number, with_extras):
    """Nested JSON-ready tree; repeated nodes and cycles are marked, not expanded."""
    shown = set()

    def visit(node, kind, path):
        record = by_number[node]
        entry = {"number": node, "kind": kind, "title": record["title"],
                 "priority": record["effective_priority"], "state": node_state(record)}
        if node in path:
            return dict(entry, cycle=True)
        if node in shown:
            return dict(entry, shown_above=True)
        shown.add(node)
        entry["children"] = [visit(target, k, path | {node}) for target, k in graph[node]]
        if with_extras:
            entry["closed_blockers"] = record["closed_blockers"]
            entry["external_blockers"] = record["external_blockers"]
        return entry
    return [visit(target, kind, {number}) for target, kind in graph[number]]


def tree_lines(entries, by_number, depth=1):
    lines = []
    for entry in entries:
        indent = "  " * depth + ("sub-issue " if entry["kind"] == "sub-issue" else "")
        if entry.get("cycle"):
            lines.append(indent + "#%d (cycle back to an issue above)" % entry["number"])
            continue
        if entry.get("shown_above"):
            lines.append(indent + "#%d (shown above)" % entry["number"])
            continue
        lines.append(indent + node_label(by_number[entry["number"]]) + " -- " + entry["state"])
        lines += tree_lines(entry["children"], by_number, depth + 1)
        for closed in entry.get("closed_blockers", []):
            lines.append("  " * (depth + 1) + "%s closed (ignored)" % closed)
        for external in entry.get("external_blockers", []):
            lines.append("  " * (depth + 1) + "%s open outside this ranking; check it by hand" % external)
    return lines


def unblock_plan(number, result):
    """What to do so `number` is no longer waiting: leaves of its prerequisite closure."""
    by_number = {record["number"]: record for record in result["issues"]}
    prerequisites, _ = adjacency(result)
    plan = {"start_now": [], "taken": [], "needs_human": [], "needs_approval": [], "blocked_elsewhere": [],
            "cycles": [c for c in result["cycles"]], "external": list(by_number[number]["external_blockers"])}
    closure = [node for node, _ in walk_prerequisites(number, prerequisites)]
    plan["cycles"] = [c for c in result["cycles"] if set(c) & set(closure)]
    for node in closure:
        record = by_number[node]
        plan["external"] += ["%s (via #%d)" % (e, node) for e in record["external_blockers"]]
        item = {"number": node, "title": record["title"], "state": node_state(record)}
        if record["human_holds"]:
            plan["needs_human"].append(dict(item, holds=record["human_holds"]))
        elif not record["approval"]:
            plan["needs_approval"].append(item)
        elif prerequisites[node]:
            continue
        elif record["eligible"]:
            plan["start_now"].append(item)
        elif record["in_progress"] or record["assignees"] or (record["claim"] and record["claim"]["active"]):
            plan["taken"].append(item)
        else:
            plan["blocked_elsewhere"].append(item)
    return plan


PLAN_TITLES = [("start_now", "start now"), ("taken", "already taken (claimed, assigned or in progress)"),
               ("needs_human", "held: needs a human"), ("needs_approval", "needs approval"),
               ("blocked_elsewhere", "blocked outside the open set"), ("external", "external blockers"),
               ("cycles", "dependency cycles to break")]


def plan_lines(plan, indent="  "):
    lines = []
    for key, title in PLAN_TITLES:
        for item in plan[key]:
            if key == "cycles":
                lines.append(indent + "%s: %s" % (title, " -> ".join("#%d" % n for n in item)))
            elif key == "external":
                lines.append(indent + "%s: %s" % (title, item))
            else:
                lines.append(indent + "%s: #%d %s -- %s" % (title, item["number"], item["title"][:60],
                                                            ", ".join(item.get("holds", [])) or item["state"]))
    return lines or [indent + "nothing open blocks it"]


def why(result, number):
    by_number = {record["number"]: record for record in result["issues"]}
    record = by_number.get(number)
    if record is None:
        return None
    prerequisites, dependents = adjacency(result)
    return {"issue": record,
            "blocked_by": dependency_tree(number, prerequisites, by_number, True),
            "unblocks": dependency_tree(number, dependents, by_number, False),
            "plan": unblock_plan(number, result)}


def render_why(result, report):
    by_number = {record["number"]: record for record in result["issues"]}
    record = report["issue"]
    lines = [node_label(record), "  state: " + node_state(record),
             "  approval: " + (", ".join(record["approval"]) or "none")]
    if record["blocker_attention"]:
        lines.append("  BLOCKER NEEDS A HUMAN: blocks %s -- %s"
                     % (", ".join("#%d" % n for n in record["needed_by"]), record["blocker_attention"]))
    lines.append("Waits for (open blockers and sub-issues, recursively):")
    lines += tree_lines(report["blocked_by"], by_number) or ["  nothing open"]
    lines += ["  %s closed (ignored)" % closed for closed in record["closed_blockers"]]
    lines += ["  %s open outside this ranking; check it by hand" % e for e in record["external_blockers"]]
    lines.append("Unblocks (dependents, recursively):")
    lines += tree_lines(report["unblocks"], by_number) or ["  nothing"]
    lines.append("To unblock #%d:" % record["number"])
    lines += plan_lines(report["plan"])
    return "\n".join(lines)


def blocked_priority(result, minimum="high"):
    """Approved, unheld urgent/high work that waits for something, with its unblock plan."""
    limit = PRIORITIES.index(minimum)
    return [{"number": r["number"], "title": r["title"], "priority": r["effective_priority"],
             "blocked_by": r["blocked_by"], "plan": unblock_plan(r["number"], result)}
            for r in result["issues"]
            if PRIORITIES.index(r["effective_priority"]) <= limit and r["approval"] and not r["human_holds"]
            and (r["prerequisites"] or r["external_blockers"])]


def render_blocked(result, entries):
    by_number = {record["number"]: record for record in result["issues"]}
    if not entries:
        return "No approved urgent/high issue is waiting for another issue."
    lines = []
    for entry in entries:
        record = by_number[entry["number"]]
        lines.append(node_label(record) + " -- " + node_state(record))
        lines += plan_lines(entry["plan"], "    ")
    return "\n".join(lines)


def render_claims(state, now, repo):
    claims = sorted(state["claims"].values(), key=lambda c: (c["repo"], c["issue"]))
    if not claims:
        return "No claims."
    rows = [["ISSUE", "AGENT", "STATE", "LEASE UNTIL", "LEFT", "CLAIMED AT", "NOTE"]]
    for claim in claims:
        left = parse_time(claim["lease_until"]) - now
        rows.append(["#%d" % claim["issue"] if claim["repo"] == repo else claim_key(claim["repo"], claim["issue"]),
                     claim["agent"], "active" if left > 0 else "expired", claim["lease_until"],
                     format_duration(left) if left > 0 else "-", claim["claimed_at"], claim.get("note", "")])
    widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]))]
    return "\n".join("  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip() for row in rows)


