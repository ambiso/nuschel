def gh_graphql(query, variables):
    command = ["gh", "api", "graphql", "-f", "query=" + query]
    for key, value in variables.items():
        if value is None:
            continue
        if isinstance(value, bool):
            command += ["-F", key + "=" + ("true" if value else "false")]
        else:
            command += ["-f", key + "=" + str(value)]
    try:
        proc = subprocess.run(command, capture_output=True, text=True,
                              timeout=120, check=False)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise FetchError("gh api graphql failed: " + str(error)) from error
    try:
        data = json.loads(proc.stdout)
    except ValueError:
        raise FetchError("gh api graphql exited %d: %s"
                         % (proc.returncode, proc.stderr.strip()[:500])) from None
    if proc.returncode != 0 or data.get("errors") or not data.get("data"):
        raise FetchError("GraphQL error: " + json.dumps(data.get("errors"))[:800]
                         + " " + proc.stderr.strip()[:300])
    return data["data"]


def gh_rest(args):
    """Run `gh api ARGS`; return (ok, message)."""
    try:
        proc = subprocess.run(["gh", "api"] + list(args), capture_output=True, text=True,
                              timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired) as error:
        return False, str(error)
    return proc.returncode == 0, (proc.stderr.strip() or proc.stdout.strip())[:300]


def mirror_in_progress(rest, repo, number, add):
    """Mirror a successful local claim (add) or release (remove) as a label."""
    if add:
        return rest(["-X", "POST", "repos/%s/issues/%d/labels" % (repo, number),
                     "-f", "labels[]=" + IN_PROGRESS])
    ok, message = rest(["-X", "DELETE", "repos/%s/issues/%d/labels/%s"
                        % (repo, number, urllib.parse.quote(IN_PROGRESS, safe=""))])
    if not ok and "Label does not exist" in message:
        return True, "label was not present"
    return ok, message


def fetch(runner, repo, with_files):
    owner, name = repo.split("/", 1)
    cursor, issues, first_repo, rate = None, [], None, None
    for page in range(MAX_PAGES):
        data = runner(QUERY, {
            "owner": owner, "name": name, "cursor": cursor,
            "withFiles": bool(with_files and page == 0),
            "mapExpr": "HEAD:" + MAP_PATH, "snapshotExpr": "HEAD:" + SNAPSHOT_PATH,
        })
        repository = data.get("repository")
        if repository is None:
            raise FetchError("repository %s not found or not readable" % repo)
        if first_repo is None:
            first_repo = repository
        rate = data.get("rateLimit") or rate
        connection = repository["issues"]
        issues.extend(connection["nodes"])
        info = connection["pageInfo"]
        if not info["hasNextPage"]:
            break
        cursor = info["endCursor"]
    else:
        raise FetchError("more than %d pages of open issues" % MAX_PAGES)
    seen = set()
    unique = []
    for issue in issues:  # a page boundary can repeat an issue; keep the first
        if issue["number"] not in seen:
            seen.add(issue["number"])
            unique.append(issue)
    return {"repository": first_repo, "issues": unique, "rateLimit": rate,
            "totalCount": first_repo["issues"]["totalCount"]}


def blob_text(blob):
    if not blob or blob.get("isTruncated") or blob.get("text") is None:
        return None
    return blob["text"]


