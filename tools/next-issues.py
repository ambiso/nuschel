    if name in ("claim", "renew", "acquire-next"):
        parser.add_argument("--lease", type=lease_seconds, default=lease_seconds(DEFAULT_LEASE),
                            help="lease length such as 90m, 24h, 2d (default %s)" % DEFAULT_LEASE)
