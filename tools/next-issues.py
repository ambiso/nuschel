def iso(timestamp):
    return time.strftime(TIME_FORMAT, time.gmtime(timestamp))


def parse_time(text):
    return calendar.timegm(time.strptime(text, TIME_FORMAT))


def claim_active(claim, now):
    return parse_time(claim["lease_until"]) > now


def claim_key(repo, number):
    return "%s#%d" % (repo, number)


def lease_seconds(text):
    match = re.match(r"^\s*(\d+)\s*([smhd])\s*$", text or "")
    if not match:
        raise argparse.ArgumentTypeError("lease must look like 90m, 24h or 2d")
    seconds = int(match[1]) * {"s": 1, "m": 60, "h": 3600, "d": 86400}[match[2]]
    if not MIN_LEASE <= seconds <= MAX_LEASE:
        raise argparse.ArgumentTypeError("lease must be between 1m and 14d")
    return seconds


def agent_name(text):
    if not AGENT_RE.match(text or ""):
        raise argparse.ArgumentTypeError("agent: 1-64 characters, letters/digits first, e.g. claude or codex")
    return text


def note_text(text):
    if len(text) > 300 or any(ord(c) < 32 or ord(c) == 127 for c in text):
        raise argparse.ArgumentTypeError("note: at most 300 characters without control characters")
    return text


def format_duration(seconds):
    seconds = int(seconds)
    if seconds >= 86400:
        return "%dd%02dh" % (seconds // 86400, seconds % 86400 // 3600)
    if seconds >= 3600:
        return "%dh%02dm" % (seconds // 3600, seconds % 3600 // 60)
    return "%dm" % max(0, seconds // 60)


def validate_state(data):
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("claims"), dict):
        raise ClaimsError("claims.json has an unexpected shape; not modifying it")
    for key, claim in data["claims"].items():
        try:
            ok = (CLAIM_KEY_RE.match(key) and isinstance(claim, dict)
                  and key == claim_key(claim["repo"], claim["issue"])
                  and isinstance(claim["issue"], int) and AGENT_RE.match(claim["agent"])
                  and isinstance(claim.get("note", ""), str)
                  and parse_time(claim["claimed_at"]) and parse_time(claim["lease_until"]))
        except (KeyError, TypeError, ValueError):
            ok = False
        if not ok:
            raise ClaimsError("claims.json entry %r is invalid; not modifying it" % key)
    return data


class ClaimStore:
    """claims.json + claims.log in one directory, serialised by flock on .lock."""

    def __init__(self, directory, lock_timeout=LOCK_TIMEOUT):
        self.directory = directory
        self.path = os.path.join(directory, "claims.json")
        self.log_path = os.path.join(directory, "claims.log")
        self.lock_timeout = lock_timeout
        self.test_delay = 0.0  # self-test only: widen the read-modify-write window

    @contextlib.contextmanager
    def locked(self, exclusive=True):
        if fcntl is None:
            raise ClaimsError("claims need POSIX fcntl.flock")
        try:
            os.makedirs(self.directory, mode=0o700, exist_ok=True)
            fd = os.open(os.path.join(self.directory, ".lock"), os.O_RDWR | os.O_CREAT, 0o600)
        except OSError as error:
            raise ClaimsError("cannot open the claims lock: %s" % error) from error
        try:
            mode = fcntl.LOCK_EX if exclusive else fcntl.LOCK_SH
            deadline = time.monotonic() + self.lock_timeout
            while True:
                try:
                    fcntl.flock(fd, mode | fcntl.LOCK_NB)
                    break
                except BlockingIOError:
                    if time.monotonic() >= deadline:
                        raise ClaimsError("timed out after %.1fs waiting for %s/.lock"
                                          % (self.lock_timeout, self.directory)) from None
                    time.sleep(0.02)
            if exclusive:
                self._remove_dead_temp_files()
            yield
        finally:
            os.close(fd)  # closing the descriptor releases the flock

    def _remove_dead_temp_files(self):
        # Writers create temp files only while holding the exclusive lock, so
        # any left over now belongs to a writer that died before os.replace.
        for name in os.listdir(self.directory):
            if name.startswith(TEMP_PREFIX) and name.endswith(TEMP_SUFFIX):
                with contextlib.suppress(OSError):
                    os.unlink(os.path.join(self.directory, name))

    def load(self):
        try:
            with open(self.path, encoding="utf-8") as handle:
                data = json.load(handle)
        except FileNotFoundError:
            data = {"version": 1, "claims": {}}
        except (OSError, ValueError) as error:
            raise ClaimsError("cannot read %s: %s; not modifying it" % (self.path, error)) from error
        if self.test_delay:
            time.sleep(self.test_delay)
        return validate_state(data)

    def read(self):
        """Current state under a shared lock; empty if the store does not exist."""
        if not os.path.isdir(self.directory):
            return {"version": 1, "claims": {}}
        with self.locked(exclusive=False):
            return self.load()

    def save(self, state):
        fd, temp = tempfile.mkstemp(prefix=TEMP_PREFIX, suffix=TEMP_SUFFIX, dir=self.directory)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(state, handle, indent=2, sort_keys=True)
                handle.write("\n")
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temp, self.path)
        except BaseException:
            with contextlib.suppress(OSError):
                os.unlink(temp)
            raise
        directory = os.open(self.directory, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)

    def log(self, entry):
        data = (json.dumps(entry, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")
        fd = os.open(self.log_path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
        try:
            while data:
                data = data[os.write(fd, data):]
            os.fsync(fd)
        finally:
            os.close(fd)


def repo_claims(state, repo):
    return {claim["issue"]: claim for claim in state["claims"].values() if claim["repo"] == repo}


def _set_claim(state, repo, number, agent, lease, note, now):
    """Claim or renew in `state`; refuse another agent's unexpired claim."""
    key = claim_key(repo, number)
    current = state["claims"].get(key)
    if current and current["agent"] != agent and claim_active(current, now):
        raise ClaimConflict("#%d is claimed by %s until %s" % (number, current["agent"], current["lease_until"]))
    if current and current["agent"] == agent:
        action = "renew"
        new = dict(current, lease_until=iso(now + lease), renewed_at=iso(now))
        if note is not None:
            new["note"] = note
    else:
        action = "takeover" if current else "claim"
        new = {"repo": repo, "issue": number, "agent": agent, "claimed_at": iso(now),
               "lease_until": iso(now + lease), "note": note or ""}
    state["claims"][key] = new
    return action, current, new


def _commit(store, state, action, claim, previous, now, via):
    store.save(state)
    store.log({"time": iso(now), "action": action, "via": via, "repo": claim["repo"],
               "issue": claim["issue"], "agent": claim["agent"],
               "lease_until": claim.get("lease_until") if action not in ("release", "force-release") else None,
               "note": claim.get("note", ""), "previous": previous, "pid": os.getpid()})


def claim_issue(store, repo, number, agent, lease, note=None, clock=time.time, via="claim"):
    with store.locked():
        now = clock()
        state = store.load()
        action, previous, new = _set_claim(state, repo, number, agent, lease, note, now)
        _commit(store, state, action, new, previous, now, via)
        return action, new, previous


def renew_claim(store, repo, number, agent, lease, clock=time.time):
    with store.locked():
        now = clock()
        state = store.load()
        current = state["claims"].get(claim_key(repo, number))
        if not current:
            raise ClaimConflict("#%d is not claimed" % number)
        if current["agent"] != agent:
            raise ClaimConflict("#%d is claimed by %s, not %s" % (number, current["agent"], agent))
        action, previous, new = _set_claim(state, repo, number, agent, lease, None, now)
        _commit(store, state, action, new, previous, now, "renew")
        return action, new, previous


def release_claim(store, repo, number, agent, force=False, clock=time.time):
    with store.locked():
        now = clock()
        state = store.load()
        key = claim_key(repo, number)
        current = state["claims"].get(key)
        if not current:
            raise ClaimConflict("#%d is not claimed" % number)
        if current["agent"] == agent:
            action = "release"
        elif not force:
            raise ClaimConflict("#%d is claimed by %s; only the holder releases it (or --force once it expires)"
                                % (number, current["agent"]))
        elif claim_active(current, now):
            raise ClaimConflict("#%d: %s's claim is active until %s; --force only releases expired claims"
                                % (number, current["agent"], current["lease_until"]))
        else:
            action = "force-release"
        del state["claims"][key]
        _commit(store, state, action, dict(current, agent=agent), current, now, "release")
        return action, current


def acquire_next(store, repo, agent, lease, note, labels, rank, clock=time.time):
    """Inside one exclusive lock: rank (excluding every unexpired claim), claim the top.

    `rank(claims, now)` returns an analyse() result; returns (record, action, claim)
    or None when nothing is eligible.
    """
    with store.locked():
        now = clock()
        state = store.load()
        result = rank(repo_claims(state, repo), now)
        candidates = [r for r in select(result, labels=labels) if r["eligible"]]
        if not candidates:
            return None
        top = candidates[0]
        action, previous, new = _set_claim(state, repo, top["number"], agent, lease, note, now)
        _commit(store, state, action, new, previous, now, "acquire-next")
        return top, action, new


