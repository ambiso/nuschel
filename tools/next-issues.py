def numbers(rows):
    return [r["number"] for r in rows]


def quiet_main(argv, **hooks):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            status = main(argv, **hooks)
        except SystemExit as exit_:
            status = exit_.code
    return status, out.getvalue(), err.getvalue()


def log_actions(store):
    with open(store.log_path, encoding="utf-8") as handle:
        return [json.loads(line)["action"] for line in handle]


def _race_claim(directory, number, agent, barrier, queue):
    store = ClaimStore(directory, lock_timeout=60)
    store.test_delay = 0.01
    barrier.wait()
    try:
        claim_issue(store, FIXTURE_REPO, number, agent, 3600)
        queue.put((agent, number))
    except ClaimConflict:
        queue.put((agent, None))
    except Exception as error:  # reported as a failure by the parent
        queue.put((agent, "error: %r" % error))


def _race_acquire(directory, agent, labels, barrier, queue):
    store = ClaimStore(directory, lock_timeout=60)
    store.test_delay = 0.01
    barrier.wait()
    try:
        got = acquire_next(store, FIXTURE_REPO, agent, 3600, None, labels,
                           lambda claims, now: fixture_rank(claims, now))
        queue.put((agent, got[0]["number"] if got else None))
    except Exception as error:
        queue.put((agent, "error: %r" % error))


def _hold_lock_then_hang(directory, ready):
    store = ClaimStore(directory, lock_timeout=10)
    with store.locked():
        # A writer that dies mid-save leaves a partial temp file behind.
        with open(os.path.join(directory, TEMP_PREFIX + "crashed" + TEMP_SUFFIX), "w") as handle:
            handle.write('{"version": 1, "claims": {')
        ready.set()
        time.sleep(120)


def race(target, argument_sets):
    import multiprocessing
    context = multiprocessing.get_context("fork")
    barrier, queue = context.Barrier(len(argument_sets)), context.Queue()
    processes = [context.Process(target=target, args=tuple(arguments) + (barrier, queue))
                 for arguments in argument_sets]
    sys.stdout.flush()
    for process in processes:
        process.start()
    results = [queue.get(timeout=120) for _ in processes]
    for process in processes:
        process.join(30)
    return results


