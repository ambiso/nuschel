def fixture_files(todo_text=FIXTURE_TODO):
    digest = hashlib.sha256(FIXTURE_TODO.encode()).hexdigest()
    snapshot = ("# Historical TODO snapshot\n\n[`TODO.md` at `%s`]\nSource SHA-256: `%s`.\n"
                % (FIXTURE_REVISION, digest)) + SNAPSHOT_SEPARATOR + todo_text
    rows = [("todo-aaaaaaaaaaaaaaaa", "checkbox", 3, 4, "issue-proposal", "12"),
            ("todo-bbbbbbbbbbbbbbbb", "checkbox", 5, 5, "issue-proposal", "99"),
            ("residual-cccccccccccccccc", "residual", 7, 7, "propose-new-residual", "26"),
            ("todo-dddddddddddddddd", "checkbox", 8, 8, "issue-proposal", "30,31,32")]
    text = ("# Historical mapping\n# source_revision=%s\n# source_sha256=%s\n# A dash denotes an absent value.\n"
            % (FIXTURE_REVISION, digest)) + "\t".join(MAP_COLUMNS) + "\n"
    for source_id, kind, start, end, disposition, issues in rows:
        text += "\t".join([source_id, kind, str(start), str(end), disposition, issues,
                           "-", "-", "-"]) + "\n"
    return text, snapshot


