def label_names(node):
    return sorted(label["name"] for label in ((node or {}).get("labels") or {}).get("nodes") or [])


def evaluate(issue, owner_login, repo, meta, rows, map_ok, labels_by_number):
    number = issue["number"]
    labels = label_names(issue)
    body = issue.get("body") or ""
    author = (issue.get("author") or {}).get("login")
    notes = []

    priorities = [label.split(":", 1)[1] for label in labels
                  if label.startswith("priority:") and label.split(":", 1)[1] in PRIORITIES]
    unknown = [label for label in labels
               if label.startswith("priority:") and label.split(":", 1)[1] not in PRIORITIES]
    if unknown:
        notes.append("ignored unknown priority label(s): " + ", ".join(unknown))
    if len(priorities) > 1:
        notes.append("several priority labels; using the highest")
    priority = min(priorities, key=PRIORITIES.index) if priorities else DEFAULT_PRIORITY

    todo = verify_todo(number, body, meta, rows, map_ok, repo)
    approval = []
    if "status:approved" in labels:
        approval.append("status:approved")
    if "source:user-request" in labels:
        approval.append("source:user-request")
    if todo["status"] == "verified":
        approval.append("todo-import")
    # The account is shared with agents, so this is not verified human provenance.
    owner_candidate = (author is not None and author == owner_login
                       and LLM_TRAILER not in body and todo["marker"] is None)
    if owner_candidate:
        notes.append("unverified owner-authored candidate (shared account); approve explicitly if intended")
    if todo["status"].startswith("unverified"):
        notes.append("todo-import " + todo["status"])

    holds = [reason for label, reason in HOLD_LABELS.items() if label in labels]
    if "status:needs-approval" in labels and "status:approved" not in labels:
        holds.insert(0, "needs-approval")
    # An open same-repository parent is in the fetched set; use its labels.
    parent = issue.get("parent") or {}
    if (parent.get("state") == "OPEN"
            and (parent.get("repository") or {}).get("nameWithOwner", repo) == repo
            and "status:deferred" in labels_by_number.get(parent.get("number"), ())):
        holds.append("parent #%d deferred" % parent["number"])
    summary = issue.get("subIssuesSummary") or {}
    open_subs = (summary.get("total") or 0) - (summary.get("completed") or 0)
    if open_subs > 0:
        holds.append("%d open sub-issue%s" % (open_subs, "" if open_subs == 1 else "s"))
    if issue["labels"].get("totalCount", 0) > len(labels):
        holds.append("labels truncated")

    assignees_node = issue.get("assignees") or {"totalCount": 0, "nodes": []}
    assignees = sorted(node["login"] for node in assignees_node["nodes"])
    if assignees_node["totalCount"] > len(assignees):
        assignees.append("+%d" % (assignees_node["totalCount"] - len(assignees)))

    blocked_by, blocker_numbers, closed_blockers, external = [], [], [], []
    connection = issue.get("blockedBy") or {"totalCount": 0, "nodes": []}
    for node in connection["nodes"]:
        other = (node.get("repository") or {}).get("nameWithOwner", repo)
        name = "#%d" % node["number"] if other == repo else "%s#%d" % (other, node["number"])
        if node.get("state") != "OPEN":
            closed_blockers.append(name)
            continue
        blocked_by.append(name)
        if other == repo:
            blocker_numbers.append(node["number"])
        else:
            external.append(name)
    unlisted = connection["totalCount"] - len(connection["nodes"])
    if unlisted > 0:
        blocked_by.append("+%d unlisted" % unlisted)
        external.append("+%d unlisted" % unlisted)
    same_repo_parent = (parent.get("state") == "OPEN"
                        and (parent.get("repository") or {}).get("nameWithOwner", repo) == repo)

    return {
        "number": number, "title": issue["title"], "url": issue.get("url"),
        "created_at": issue["createdAt"], "author": author, "labels": labels,
        "priority": priority, "priority_source": "label" if priorities else "default",
        "effective_priority": priority, "prerequisite_for": [],
        "thumbs_up": (issue.get("reactions") or {}).get("totalCount", 0),
        "approval": approval, "owner_authored_candidate": owner_candidate,
        "todo_import": todo, "blocked_by": blocked_by,
        "closed_blockers": closed_blockers, "external_blockers": external,
        "_blockers": blocker_numbers, "_parent": parent.get("number") if same_repo_parent else None,
        "in_progress": IN_PROGRESS in labels, "assignees": assignees, "holds": holds,
        # Open sub-issues are structural (the parent waits for them), not a human hold.
        "human_holds": [hold for hold in holds if not SUBISSUE_HOLD_RE.match(hold)],
        "claim": None, "notes": notes,
    }


def find_cycles(graph):
    """Strongly connected components with a cycle (iterative Tarjan)."""
    index, low, on_stack, stack, cycles, counter = {}, {}, set(), [], [], 0
    for root in sorted(graph):
        if root in index:
            continue
        index[root] = low[root] = counter
        counter += 1
        stack.append(root)
        on_stack.add(root)
        work = [(root, iter(graph[root]))]
        while work:
            node, edges = work[-1]
            for target, _ in edges:
                if target not in index:
                    index[target] = low[target] = counter
                    counter += 1
                    stack.append(target)
                    on_stack.add(target)
                    work.append((target, iter(graph[target])))
                    break
                if target in on_stack:
                    low[node] = min(low[node], index[target])
            else:
                work.pop()
                if work:
                    low[work[-1][0]] = min(low[work[-1][0]], low[node])
                if low[node] == index[node]:
                    component = []
                    while True:
                        member = stack.pop()
                        on_stack.discard(member)
                        component.append(member)
                        if member == node:
                            break
                    if len(component) > 1 or any(target == node for target, _ in graph[node]):
                        cycles.append(sorted(component))
    return sorted(cycles)


def walk_prerequisites(start, graph):
    """Breadth-first over prerequisites; yields (node, path from start to its dependent).
    Each node is visited once, so cycles terminate."""
    parents, queue, head = {start: None}, [start], 0
    while head < len(queue):
        node = queue[head]
        head += 1
        for target, _ in graph[node]:
            if target in parents:
                continue
            parents[target] = node
            queue.append(target)
            path, step = [], node
            while step is not None:
                path.append(step)
                step = parents[step]
            yield target, path[::-1]


def dependency_graph(records):
    """{number: [(prerequisite, kind)]} over open issues in the fetched set."""
    by_number = {record["number"]: record for record in records}
    graph = {number: set() for number in by_number}
    for record in records:
        for number in record["_blockers"]:
            if number in by_number:
                graph[record["number"]].add((number, "blocked-by"))
            else:
                record["external_blockers"].append("#%d (not fetched)" % number)
        parent = record["_parent"]
        if parent in by_number and parent != record["number"]:
            graph[parent].add((record["number"], "sub-issue"))
    return {number: sorted(edges) for number, edges in graph.items()}


def resolve_dependencies(records):
    """Transitive priority over prerequisites; returns (graph, cycles, attention).

    Approval never flows along a dependency: an unapproved or held prerequisite of
    approved, unheld work stays ineligible and is listed in `attention`."""
    by_number = {record["number"]: record for record in records}
    graph = dependency_graph(records)
    for record in records:
        record["prerequisites"] = [number for number, _ in graph[record["number"]]]
        record["prerequisite_for"] = sorted(n for n, edges in graph.items()
                                            if any(target == record["number"] for target, _ in edges))
        record.update(priority_via=[], needed_by=[], blocker_attention=None, in_cycle=False,
                      sort_thumbs=record["thumbs_up"])
    roots = [r for r in records if r["approval"] and not r["human_holds"]]
    reached = {}
    for root in roots:
        rank = (PRIORITIES.index(root["priority"]), -root["thumbs_up"])
        tie = (root["created_at"], root["number"])
        for node, path in walk_prerequisites(root["number"], graph):
            reached.setdefault(node, []).append((rank, len(path), tie, path))
    attention = []
    for number, candidates in reached.items():
        record = by_number[number]
        candidates.sort()
        (priority_rank, thumbs), _, _, path = candidates[0]
        record["needed_by"] = sorted({c[3][0] for c in candidates})
        if priority_rank < PRIORITIES.index(record["priority"]):
            record["effective_priority"] = PRIORITIES[priority_rank]
            record["priority_source"] = "prerequisite"
            record["priority_via"] = path
            record["sort_thumbs"] = -thumbs
        if record["human_holds"]:
            record["blocker_attention"] = "held: " + ", ".join(record["human_holds"])
        elif not record["approval"]:
            record["blocker_attention"] = "needs approval"
        if record["blocker_attention"]:
            attention.append({"number": number, "title": record["title"], "kind": record["blocker_attention"],
                              "blocks": record["needed_by"], "via": path})
    cycles = find_cycles(graph)
    for cycle in cycles:
        for number in cycle:
            by_number[number]["in_cycle"] = True
            by_number[number]["notes"].append("dependency cycle: " + " -> ".join("#%d" % n for n in cycle))
    return graph, cycles, sorted(attention, key=lambda a: a["number"])


def analyse(fetched, map_text, snapshot_text, include_in_progress=False, owner_login=None,
            include_assigned=False, claims=None, viewer=None, now=None):
    """Rank open issues. `claims` maps issue number to a local claim; claims by
    `viewer` stay eligible, every other unexpired claim makes an issue ineligible."""
    repository = fetched["repository"]
    repo = repository["nameWithOwner"]
    owner_login = owner_login or repository["owner"]["login"]
    now = time.time() if now is None else now
    claims = claims or {}
    meta, rows, problems = load_map(map_text, snapshot_text)
    map_ok = not problems
    labels_by_number = {issue["number"]: label_names(issue) for issue in fetched["issues"]}
    records = [evaluate(issue, owner_login, repo, meta, rows, map_ok, labels_by_number)
               for issue in fetched["issues"]]
    graph, cycles, attention = resolve_dependencies(records)
    for record in records:
        reasons = []
        if not record["approval"]:
            reasons.append("no approval basis" + (" (unverified owner-authored candidate)"
                                                  if record["owner_authored_candidate"] else ""))
        if record["blocked_by"]:
            reasons.append("blocked by " + ", ".join(record["blocked_by"]))
        reasons += ["hold: " + hold for hold in record["holds"]]
        if record["in_progress"] and not include_in_progress:
            reasons.append("in progress")
        if record["assignees"] and not include_assigned:
            reasons.append("assigned: " + ",".join(record["assignees"]))
        claim = claims.get(record["number"])
        if claim:
            active = claim_active(claim, now)
            record["claim"] = {"agent": claim["agent"], "lease_until": claim["lease_until"],
                               "claimed_at": claim["claimed_at"], "note": claim.get("note", ""),
                               "active": active}
            if active and claim["agent"] != viewer:
                reasons.append("claimed by %s until %s" % (claim["agent"], claim["lease_until"]))
            elif not active:
                record["notes"].append("claim by %s expired %s; reclaimable with claim/acquire-next"
                                       % (claim["agent"], claim["lease_until"]))
        record["eligible"] = not reasons
        record["ineligible_reasons"] = reasons
        del record["_blockers"], record["_parent"]
    records.sort(key=lambda r: (PRIORITIES.index(r["effective_priority"]), -r["sort_thumbs"],
                                r["created_at"], r["number"]))
    queue = 0
    for record in records:
        if record["eligible"]:
            queue += 1
            record["queue_position"] = queue
        else:
            record["queue_position"] = None
    branch = repository.get("defaultBranchRef") or {}
    unverified = sum(1 for r in records if r["todo_import"]["status"].startswith("unverified"))
    warnings = list(problems)
    if unverified:
        warnings.append("%d issue(s) with an unverified TODO-import marker" % unverified)
    warnings += ["dependency cycle: " + " -> ".join("#%d" % n for n in cycle) for cycle in cycles]
    return {
        "repository": repo,
        "default_branch": branch.get("name"),
        "default_branch_oid": (branch.get("target") or {}).get("oid"),
        "owner_login": owner_login,
        "open_issues": fetched.get("totalCount", len(records)),
        "fetched_issues": len(records),
        "eligible_issues": queue,
        "include_in_progress": include_in_progress,
        "include_assigned": include_assigned,
        "viewer": viewer,
        "active_claims": sum(1 for c in claims.values() if claim_active(c, now)),
        "todo_map": {"verified": map_ok, "rows": len(rows),
                     "source_revision": meta.get("source_revision"),
                     "source_sha256": meta.get("source_sha256"), "problems": problems},
        "rate_limit": fetched.get("rateLimit"),
        "warnings": warnings,
        "attention_blockers": attention,
        "cycles": cycles,
        "dependency_edges": [[blocker, dependent, kind] for dependent, edges in sorted(graph.items())
                             for blocker, kind in edges],
        "issues": records,
    }


def select(result, show_all=False, labels=(), limit=0):
    chosen = [r for r in result["issues"]
              if (show_all or r["eligible"]) and all(label in r["labels"] for label in labels)]
    return chosen[:limit] if limit and limit > 0 else chosen


