"""List open Nuschl issues in the AGENTS.md queue-selection order, and claim them.

Read-only ranking. Standard library only. Uses the caller's `gh` authentication
for one paginated GraphQL query (about two pages for 200 open issues); the TODO
issue map and its historical snapshot ride along in the first page.

Order: effective priority (urgent > high > medium > low; unset = medium; the
highest of several priority labels; an open prerequisite inherits the highest
priority of the approved, unheld work it transitively unblocks), then
descending thumbs-up on the original post (for a lifted prerequisite: of the
dependent chain's root), then older issue first, then lower number.

Prerequisites: open `blockedBy` issues, and open sub-issues of a parent. A
prerequisite inherits priority but never approval: it needs its own approval
basis. Unapproved or held prerequisites of approved work are reported so a
human can approve or release them. Cycles are detected and reported.

Eligible = approved AND not blocked AND not held AND not in progress AND not
assigned AND not under another agent's unexpired local claim.

Approval basis (any one suffices): status:approved, source:user-request, or a
verified TODO-import marker. An owner-authored-looking post (author is the
repository owner, no "LLM-generated by" trailer, no import marker) is only an
unverified candidate: the account is shared, so it never approves anything.
A TODO-import marker is verified only when the map/snapshot pair checks out
(snapshot's embedded TODO hashes to the map's source_sha256; checkbox rows
point at unchecked checkboxes) and the body links TODO.md at the map's source
revision with the exact line range of a map row that lists this issue number.
A copied marker or link fails, because the map names the original issue.

Holds: status:needs-approval without status:approved, status:deferred,
type:tracking, type:operator-action, duplicate, invalid, wontfix, question,
an open parent marked status:deferred, or open sub-issues. Assignees are
reported as "assigned: <logins>"; Claude and Codex both act through the
owner's account, so an assignee means "someone owns it", not who.

Claims (same machine, shared by Claude and Codex): claims.json under the claims
directory, changed only while holding an exclusive flock on its .lock, written
via temp file + fsync + os.replace, and every change appended to claims.log.
Subcommands: claim, release, renew, claims, acquire-next (rank and claim the
top eligible issue inside one lock). GitHub label mirroring (--github) follows
a successful local change and is never the source of truth.
"""

