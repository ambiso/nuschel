def fixture_runner(map_text=None, snapshot=None, pages=None):
    if map_text is None:
        map_text, snapshot = fixture_files()
    first, second = pages or fixture_pages()
    calls = []

    def runner(query, variables):
        assert "blockedBy" in query and "assignees" in query and variables["owner"] == "ambiso"
        cursor = variables.get("cursor")
        calls.append((cursor, variables["withFiles"]))
        assert cursor in (None, "CUR1"), cursor
        nodes, info = (first, {"hasNextPage": True, "endCursor": "CUR1"}) if cursor is None else \
            (second, {"hasNextPage": False, "endCursor": "CUR2"})
        repository = {
            "nameWithOwner": FIXTURE_REPO, "owner": {"login": "ambiso"},
            "defaultBranchRef": {"name": "main", "target": {"oid": "f" * 40}},
            "issues": {"totalCount": len(first) + len(second), "pageInfo": info, "nodes": nodes},
        }
        if variables["withFiles"]:
            repository["todoMap"] = {"oid": "1" * 40, "text": map_text, "isTruncated": False}
            repository["todoSnapshot"] = {"oid": "2" * 40, "text": snapshot, "isTruncated": False}
        return {"rateLimit": {"cost": 1, "remaining": 4999, "resetAt": "x"}, "repository": repository}
    return runner, calls


