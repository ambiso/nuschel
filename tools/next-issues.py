def parse_map(text):
    meta, rows, header = {}, {}, None
    for number, line in enumerate(text.split("\n"), 1):
        if not line.strip():
            continue
        if line.startswith("#"):
            for key, value in re.findall(r"(\w+)=(\S+)", line):
                meta[key] = value
            continue
        columns = line.split("\t")
        if header is None:
            if columns != MAP_COLUMNS:
                raise MapError("unexpected map header: %r" % columns)
            header = columns
            continue
        if len(columns) != len(header):
            raise MapError("map line %d has %d columns" % (number, len(columns)))
        row = dict(zip(header, columns, strict=True))
        if not SOURCE_ID_RE.match(row["source_id"]):
            raise MapError("map line %d: bad source id %r" % (number, row["source_id"]))
        if row["source_id"] in rows:
            raise MapError("duplicate source id " + row["source_id"])
        try:
            row["start_line"], row["end_line"] = int(row["start_line"]), int(row["end_line"])
            row["issues"] = set() if row["issue_numbers"] == "-" else {
                int(value) for value in row["issue_numbers"].split(",")}
        except ValueError:
            raise MapError("map line %d: bad number" % number) from None
        rows[row["source_id"]] = row
    if header is None:
        raise MapError("map has no header")
    for key in ("source_revision", "source_sha256"):
        if not re.match(r"^[0-9a-f]{40,64}$", meta.get(key, "")):
            raise MapError("map lacks " + key)
    return meta, rows


def load_map(map_text, snapshot_text):
    """Return (meta, rows, problems); rows count only when problems is empty."""
    if map_text is None:
        return {}, {}, ["TODO map unavailable"]
    try:
        meta, rows = parse_map(map_text)
    except MapError as error:
        return {}, {}, ["TODO map invalid: %s" % error]
    problems = []
    if snapshot_text is None:
        problems.append("TODO snapshot unavailable")
    else:
        index = snapshot_text.find(SNAPSHOT_SEPARATOR)
        if index < 0:
            problems.append("snapshot separator missing")
        else:
            preface, source = snapshot_text[:index], snapshot_text[index + len(SNAPSHOT_SEPARATOR):]
            digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
            if digest != meta["source_sha256"]:
                problems.append("snapshot TODO sha256 %s != map %s"
                                % (digest[:12], meta["source_sha256"][:12]))
            if meta["source_sha256"] not in preface or meta["source_revision"] not in preface:
                problems.append("snapshot preface does not name the map's source")
            lines = source.split("\n")
            for row in rows.values():
                start, end = row["start_line"], row["end_line"]
                if not 1 <= start <= end <= len(lines):
                    problems.append("%s: lines %d-%d outside snapshot" % (row["source_id"], start, end))
                elif row["source_kind"] == "checkbox" and not re.match(r"\s*- \[ \]", lines[start - 1]):
                    problems.append("%s: line %d is not an unchecked checkbox" % (row["source_id"], start))
    return meta, rows, problems[:5]


def verify_todo(number, body, meta, rows, map_ok, repo):
    markers = MARKER_RE.findall(body)
    cited = sorted(set(CITED_ID_RE.findall(body)))
    listed = sorted(row["source_id"] for row in rows.values() if number in row["issues"])
    result = {"marker": markers[0] if markers else None, "matched_ids": [],
              "mismatched_ids": [], "map_listed_ids": listed if map_ok else []}
    if not markers:
        result["status"] = "absent" if not (map_ok and listed) else "unverified: map lists issue but marker missing"
        return result
    if not map_ok:
        result["status"] = "unverified: map/snapshot check failed"
        return result
    # A source link at the map's revision whose exact line range is a map row
    # listing this issue. Copied markers/links fail: the map names the original.
    links = {(int(start), int(end or start))
             for revision, start, end in re.findall(TODO_LINK % re.escape(repo), body)
             if revision == meta["source_revision"]}
    result["matched_ids"] = sorted(
        row["source_id"] for row in rows.values()
        if number in row["issues"] and (row["start_line"], row["end_line"]) in links)
    result["mismatched_ids"] = [i for i in cited if i not in result["matched_ids"]]
    if result["matched_ids"]:
        result["status"] = "verified"
    elif not links and not cited:
        result["status"] = "unverified: marker without a source link"
    else:
        result["status"] = "unverified: source links do not map to this issue"
    return result


